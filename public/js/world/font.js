function build(src, h) {
  const glyphs = new Map();
  for (const ch of Object.keys(src)) {
    const rows = src[ch].split('/');
    glyphs.set(ch, { w: rows[0].length, rows });
  }
  return { h, glyphs, cache: new Map() };
}

