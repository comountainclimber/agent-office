export const SMALL = build(SMALL_SRC, 5);

const FOLD = { '–': '-', '‐': '-', '‑': '-', '’': "'", '‘': "'", '“': '"', '”': '"', '[': '(', ']': ')', '{': '(', '}': ')', '\\': '/', '|': '/', '~': '-', ';': ':', '`': "'", '^': "'", $: 'S' };

export function norm(text) {
  let out = '';
  for (const raw of String(text ?? '').toUpperCase()) {
    const ch = FOLD[raw] || raw;
    out += ch;
  }
  return out;
}

function glyph(font, ch) {
  return font.glyphs.get(ch) || font.glyphs.get('?');
}

/** Width in pixels of already-normalised or raw text. */
export function textWidth(text, font = SMALL) {
  const t = norm(text);
  let w = 0;
  for (const ch of t) w += glyph(font, ch).w + 1;
  return Math.max(0, w - 1);
}

/** Clip text to at most `maxW` pixels, adding an ellipsis glyph when something was cut. */
export function clipText(text, maxW, font = SMALL) {
  const t = norm(text);
  if (textWidth(t, font) <= maxW) return t;
  const ell = glyph(font, '…').w + 1;
  let w = 0;
  let out = '';
  for (const ch of t) {
    const gw = glyph(font, ch).w + 1;
    if (w + gw + ell - 1 > maxW) break;
    w += gw;
    out += ch;
  }
  return out.replace(/[\s\-—.,:]+$/, '') + '…';
}

/** Draw text directly (top-left at x,y). Returns the x after the last glyph. */
export function drawText(g, text, x, y, colour, font = SMALL) {
  const t = norm(text);
  g.fillStyle = colour;
  let cx = x;
  for (const ch of t) {
    const gl = glyph(font, ch);
    for (let j = 0; j < gl.rows.length; j++) {
      const row = gl.rows[j];
      let run = -1;
      for (let i = 0; i <= row.length; i++) {
        const on = i < row.length && row[i] === '1';
        if (on && run < 0) run = i;
        if (!on && run >= 0) {
          g.fillRect(cx + run, y + j, i - run, 1);
          run = -1;
        }
      }
    }
    cx += gl.w + 1;
  }
  return cx - 1;
}

/** Cached little canvas with the text on it (transparent background). */
export function textSprite(text, colour, font = SMALL) {
  const t = norm(text);
  const key = colour + '|' + t;
  let c = font.cache.get(key);
  if (c) return c;
  if (font.cache.size > 1500) font.cache.clear();
  c = makeCanvas(Math.max(1, textWidth(t, font)), font.h);
  drawText(ctx2d(c), t, 0, 0, colour, font);
  font.cache.set(key, c);
  return c;
}
