function runs(row) {
  const out = [];
  let i = 0;
  while (i < row.length) {
    if (row[i] === '#') {
      let j = i;
      while (j < row.length && row[j] === '#') j++;
      out.push(i, j - i);
      i = j;
    } else i++;
  }
  return out;
}

function compile(table, h) {
  const g = {};
  for (const [ch, def] of Object.entries(table)) {
    const rows = def.split('/').slice(0, h);
    while (rows.length < h) rows.push('');
    const w = Math.max(...rows.map((r) => r.length));
    g[ch] = { w, rows: rows.map(runs) };
  }
  return { h, g };
}

const FONTS = { 5: compile(SMALL, 5), 7: compile(LARGE, 7) };

function glyph(font, ch) {
  const f = FONTS[font];
  return f.g[ch] || f.g[ch.toUpperCase()] || FONTS[5].g[ch] || f.g['?'];
}

export function textWidth(str, font = 5, scale = 1) {
  let w = 0;
  for (const ch of String(str)) w += glyph(font, ch).w + 1;
  return Math.max(0, (w - 1) * scale);
}

/** Draw text with its top-left at x,y (integers). Returns the width drawn. */
export function drawText(ctx, str, x, y, color, font = 5, scale = 1) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of String(str)) {
    const gl = glyph(font, ch);
    for (let r = 0; r < gl.rows.length; r++) {
      const row = gl.rows[r];
      for (let k = 0; k < row.length; k += 2) ctx.fillRect(cx + row[k] * scale, y + r * scale, row[k + 1] * scale, scale);
    }
    cx += (gl.w + 1) * scale;
  }
  return cx - x - scale;
}

const cache = new Map();
/** A cached canvas holding the rendered text (1 logical px per font px). */
export function textCanvas(str, color, font = 5) {
  const key = font + '|' + color + '|' + str;
  let c = cache.get(key);
  if (c) return c;
  if (cache.size > 800) cache.clear();
  c = document.createElement('canvas');
  c.width = Math.max(1, textWidth(str, font));
  c.height = font;
  drawText(c.getContext('2d'), str, 0, 0, color, font);
  cache.set(key, c);
  return c;
}

/**
 * Fit a label into at most maxLines lines of maxChars characters, breaking after - _ . / and spaces.
 * The last line takes whatever is left and is cut with an ellipsis, so the start of a name always survives.
 */
export function fitLabel(str, maxChars, maxLines = 2) {
  const rest = String(str).toUpperCase().match(/[^-_./ ]*[-_./ ]?/g).filter(Boolean);
  const lines = [];
  let cur = '';
  let hard = false;
  while (rest.length && lines.length < maxLines - 1) {
    const p = rest[0];
    if ((cur + p).trimEnd().length <= maxChars) { cur += p; rest.shift(); }
    else if (cur) { lines.push(cur.trimEnd()); cur = ''; }
    else { lines.push(p.slice(0, maxChars)); rest[0] = p.slice(maxChars); hard = true; }
  }
  let last = (cur + rest.join('')).trimEnd();
  let fits = true;
  if (last.length > maxChars) { last = last.slice(0, maxChars - 1).replace(/[-_./ ]+$/, '') + '…'; fits = false; }
  if (last) lines.push(last);
  return { lines, fits, hard };
}

/** Smallest line length between lo and hi at which the label fits on two lines untruncated (hi if none). */
export function minChars(str, lo = 8, hi = 15) {
  let soft = 0;
  for (let n = lo; n <= hi; n++) {
    const r = fitLabel(str, n, 2);
    if (r.fits && !r.hard) return n;
    if (r.fits && !soft) soft = n;
  }
  return soft || hi;
}
